/*
 * Builds the page's importmap for 3rd-party libraries (three.js, lil-gui),
 * resolved relative to this script's own URL.
 *
 * The local-vs-CDN choice and sha384 integrity hashes are baked into the
 * VENDOR block by scripts/generate-importmap.mjs; CI regenerates and diffs it.
 *   npm run importmap:local   # vendored three.js/ + node_modules/
 *   npm run importmap         # all-CDN (the committed default)
 * Do NOT commit a `local` VENDOR block — it breaks the live deploy.
 *
 * Page-specific imports: assign window.daydreamExtraImports = { name: '...' }
 * before this script.
 */
(function () {
  // === GENERATED by scripts/generate-importmap.mjs — do not edit by hand ===
  // Per-library resolution baked at build time. 'cdn' (default, deploy-safe)
  // or 'local' (offline dev with vendored dirs). Versions come from
  // package.json, integrity hashes from the installed node_modules copy of
  // each pinned version. Regenerate, don't hand-edit.
  const VENDOR = { three: 'cdn', lilGui: 'cdn' };
  const THREE_VERSION = '0.183.1';
  const LIL_GUI_VERSION = '0.21.0';
  const INTEGRITY = {
    three: 'sha384-tDnOBR4yGB9V87jI7t3/bA2vGgtDUaOU+poekPUUnV7O3yEhLb4f+gRAXEd6eoCN',
    lilGui: 'sha384-6d+WSm8Yon/yBd0igp6VIN3j2vn1gYETuplvJw4ARkxsNorY87Y3rVaTkuebZ17j',
    threeAddons: {
      'controls/OrbitControls.js': 'sha384-qwbKZfqvfut7iKUj5OTm9S0ZtyKO8qwf6tgArWhWhvjzpRG9qEN88IL6J8gVOZOx',
      'renderers/CSS2DRenderer.js': 'sha384-z6mvHHI+Qnu2M3bcgZ/iybgTVGXzWGHgPkH8lSvg0AYfVzzQm62z5G1K00co2ncK',
    },
    threeFiles: {
      'build/three.core.js': 'sha384-T0d5qlOvyPT92JVj73IjXSVeqEuJIXH7hs2dZzcsSyRv/ugCdA1BDA07IZZ1QryO',
    },
  };
  // === END GENERATED ===

  // currentScript is null unless this runs as a classic synchronous <script>.
  const selfScript = document.currentScript;
  if (!selfScript) {
    throw new Error('vendor-importmap.js: document.currentScript is null — load ' +
      'this as a classic <script> (not type="module" or a deferred/dynamic ' +
      'import); it must run synchronously to detect its own path and inject the ' +
      'importmap before modules load.');
  }
  const ROOT = new URL('.', selfScript.src);
  const EXTRA = window.daydreamExtraImports || {};

  const CDN = 'https://cdn.jsdelivr.net/npm';

  const abs = (path) => new URL(path, ROOT).href;

  const threeBase = VENDOR.three === 'local'
    ? abs('three.js/')
    : `${CDN}/three@${THREE_VERSION}/`;
  const lilGui = VENDOR.lilGui === 'local'
    ? abs('node_modules/lil-gui/dist/lil-gui.esm.min.js')
    : `${CDN}/lil-gui@${LIL_GUI_VERSION}/dist/lil-gui.esm.min.js`;

  // Core keys override EXTRA.
  const imports = Object.assign({}, EXTRA, {
    'three': `${threeBase}build/three.module.js`,
    'three/addons/': `${threeBase}examples/jsm/`,
    'lil-gui': lilGui,
  });

  // SRI for CDN-served modules, keyed by resolved URL (one entry per addon).
  // Same-origin modules are unpinned.
  const integrity = {};
  if (VENDOR.three === 'cdn') {
    integrity[imports['three']] = INTEGRITY.three;
    for (const [path, hash] of Object.entries(INTEGRITY.threeAddons)) {
      integrity[`${threeBase}examples/jsm/${path}`] = hash;
    }
    for (const [path, hash] of Object.entries(INTEGRITY.threeFiles)) {
      integrity[`${threeBase}${path}`] = hash;
    }
  }
  if (VENDOR.lilGui === 'cdn') integrity[lilGui] = INTEGRITY.lilGui;

  const map = { imports };
  if (Object.keys(integrity).length) map.integrity = integrity;

  const s = document.createElement('script');
  s.type = 'importmap';
  s.textContent = JSON.stringify(map);
  document.head.appendChild(s);
})();
